<?php
/**
 * config.php
 * Βασικές ρυθμίσεις της εφαρμογής.
 */

// Ζώνη ώρας
date_default_timezone_set('Europe/Athens');

// --- Κωδικός διαχείρισης --------------------------------------------------
// Ο κωδικός ΔΕΝ ορίζεται εδώ. Στο πρώτο άνοιγμα της σελίδας "Σύνδεση", όταν
// δεν έχει οριστεί ακόμα κωδικός, η εφαρμογή ζητά να δημιουργήσεις έναν και
// αποθηκεύει μόνο το bcrypt hash του στη βάση δεδομένων. Αλλαγή κωδικού:
// από τη σελίδα Ρυθμίσεις.
//
// Μόνο για αναβάθμιση από παλιά έκδοση: αν υπάρχει το (παλιό) config.local.php
// με APP_PASSWORD_HASH, το hash εισάγεται μία φορά στη βάση. Μετά μπορείς να το σβήσεις.
if (is_file(__DIR__ . '/config.local.php')) {
    require __DIR__ . '/config.local.php';
}

// --- Διαδρομές -------------------------------------------------------------
define('APP_ROOT', __DIR__);
define('DB_PATH', __DIR__ . '/data/subscriptions.sqlite');

// --- Session -----------------------------------------------------------
if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

// --- Εμφάνιση σφαλμάτων (απενεργοποίησε σε production αν θέλεις) ---------
error_reporting(E_ALL);
ini_set('display_errors', '1');
